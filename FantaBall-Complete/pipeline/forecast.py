"""Weekly forecast: build the current league from the data (rounds played so far count), simulate the rest of
the season (module 1, saved to data/sim/, last 10 kept), score it under the standard rules (module 2), save the forecast
table, and hand the league to the app (mobile/assets/league.js). No backtest."""
import subprocess, datetime, json, pathlib
import pandas as pd
import calibrate as C
import backtest as B
from common import CURRENT, DATA, RAW

APP = pathlib.Path(__file__).resolve().parents[1] / 'mobile' / 'assets' / 'league.js'


def rounds_played(season=CURRENT):
    """Rounds whose every match is finished (FotMob calendar)."""
    m = pd.read_csv(RAW / 'fotmob' / f'matches_{season}.csv')
    done = m.groupby('round').finished.all()
    return int(done[done].index.max()) if done.any() else 0


KEEP_SEASON_FILES = 10


def prune_season_files(sim_dir):
    """Keep the 10 most recent season files in data/sim; older ones are listed in archive.csv and removed from
    the working tree (they stay in git history: `git log --all -- data/sim/<file>` then `git show <commit>:<path>`)."""
    key = lambda f: (f.name.split('_')[1], int(f.name.split('_round_')[1].split('.')[0]), f.stat().st_mtime)
    files = sorted(sim_dir.glob('season_*_after_round_*.fbsim.*'), key=key)
    old = files[:-KEEP_SEASON_FILES]
    if not old:
        return
    log = sim_dir / 'archive.csv'
    rows = pd.DataFrame([{'file': f.name, 'bytes': f.stat().st_size, 'archived_on': str(datetime.date.today()),
                          'retrieve': f'git log --all -- FantaBall-Complete/data/sim/{f.name}'} for f in old])
    rows.to_csv(log, mode='a', header=not log.exists(), index=False)
    for f in old:
        f.unlink()
    print('archived', len(old), 'old season files')


SIMULATIONS, BURN_IN, DETAIL = 15000, 5000, 255   # 20,000 simulated seasons, the first 5,000 discarded


def main(n=SIMULATIONS):
    played = rounds_played()
    lg = C.build_league(CURRENT, played)
    APP.write_text('// Generated by pipeline/forecast.py — real Serie A league for the app. Do not edit by hand.\n'
                   f'const LEAGUE_DATA={json.dumps(lg, separators=(",", ":"))};\n')
    B.N = n
    B.CONFIG = {**B.CONFIG, 'season': CURRENT, 'rounds': 38 - played}
    # Module 1: the simulated season, saved for re-scoring under any rules (data/sim, committed; last 10 kept)
    sim_dir = DATA / 'sim'; sim_dir.mkdir(exist_ok=True)
    season_file = sim_dir / f'season_{CURRENT}_after_round_{played}.fbsim.br'
    d = DATA / 'forecasts'; d.mkdir(exist_ok=True)
    # Bootstrap: the history resampled by matchday and the model refitted BOOT_K times; each simulated season uses one refit
    reps = C.bootstrap_leagues(CURRENT, played)
    (d / 'bootstrap_leagues.json').write_text(json.dumps(reps, separators=(',', ':')))   # also used by the next-match correlations
    B.run_season(lg, season_file, summary=d / 'matchday_simulation_latest.csv.gz', n=n, burn_in=BURN_IN, detail=DETAIL, replicates=reps)   # module 1's matchday table
    (sim_dir / 'season_latest.fbsim.br').write_bytes(season_file.read_bytes())   # identical content: stored once by git
    prune_season_files(sim_dir)
    # Module 2: xFM under the standard rules (any league's rules: pipeline/score_season.js)
    sim = B.score_season(season_file, corr_prefix=d / 'correlation', matchdays=d / 'matchday_xfm_latest.csv.gz')     # + player-by-player correlation matrices
    meta = pd.DataFrame(lg['players'])[['id', 'qi', 'start', 'injuryRisk', 'injuredFor']]
    out = sim.merge(meta, on='id')[['id', 'name', 'team', 'role', 'qi', 'xfm', 'xfmLow', 'xfmHigh', 'rated', 'glo', 'ghi', 'expected',
                                     'vote', 'goals', 'assists', 'penScored', 'integrita', 'titolarita', 'injuredFor']]
    out = out.sort_values('expected', ascending=False).round(3)
    stamp = str(datetime.date.today())
    out.to_csv(d / f'xfm_{stamp}.csv', index=False); out.to_csv(d / 'xfm_latest.csv', index=False)
    # Next matchday only: correlations across 15,000 draws of that one round (teammates and the two opposing clubs)
    subprocess.run(['node', '--max-old-space-size=8000', str(pathlib.Path(__file__).parent / 'match_correlations.js'), str(APP),
                    str(d / 'correlation_next_match.json'), str(n), str(d / 'bootstrap_leagues.json')], check=True)
    (d / 'bootstrap_leagues.json').unlink()
    print(f'forecast {CURRENT} after round {played}: {len(out)} players, rounds left {38 - played}')
    print(out.groupby('role').head(3)[['name', 'team', 'role', 'xfm', 'rated', 'expected']].to_string(index=False))


if __name__ == '__main__':
    main()
